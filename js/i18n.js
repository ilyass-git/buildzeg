(function() {
    var STORAGE_KEY = 'buildzeg-lang';
    var ATTRS = ['alt', 'placeholder', 'aria-label'];
    var originals = new Map();      // text node -> original English text
    var metaOriginals = new Map();  // element -> original English attribute values
    var originalTitle = document.title;
    var lang = 'en';

    function normalize(text) {
        return text.replace(/\s+/g, ' ').trim();
    }

    function translate(english) {
        if (lang !== 'fr') return english;
        var key = normalize(english);
        return Object.prototype.hasOwnProperty.call(FR, key) ? FR[key] : english;
    }

    function translateTextNode(node) {
        if (!originals.has(node)) originals.set(node, node.nodeValue);
        var original = originals.get(node);
        var key = normalize(original);
        if (!key) return;
        if (lang === 'fr' && Object.prototype.hasOwnProperty.call(FR, key)) {
            // Keep the surrounding whitespace so the layout does not change
            var lead = original.match(/^\s*/)[0];
            var trail = original.match(/\s*$/)[0];
            node.nodeValue = lead + FR[key] + trail;
        } else {
            node.nodeValue = original;
        }
    }

    function translateAttributes(el) {
        if (!metaOriginals.has(el)) {
            var saved = {};
            ATTRS.forEach(function(attr) {
                if (el.hasAttribute(attr)) saved[attr] = el.getAttribute(attr);
            });
            metaOriginals.set(el, saved);
        }
        var saved = metaOriginals.get(el);
        Object.keys(saved).forEach(function(attr) {
            el.setAttribute(attr, translate(saved[attr]));
        });
    }

    function applyLanguage(newLang) {
        lang = newLang === 'fr' ? 'fr' : 'en';
        document.documentElement.setAttribute('lang', lang);
        document.title = translate(originalTitle);

        var description = document.querySelector('meta[name="description"]');
        if (description) {
            if (!description.hasAttribute('data-original-content')) {
                description.setAttribute('data-original-content', description.getAttribute('content'));
            }
            description.setAttribute('content', translate(description.getAttribute('data-original-content')));
        }

        var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
            acceptNode: function(node) {
                var parent = node.parentNode;
                if (!parent || parent.closest('script, style, [data-lang-switch]')) return NodeFilter.FILTER_REJECT;
                return NodeFilter.FILTER_ACCEPT;
            }
        });
        var nodes = [];
        while (walker.nextNode()) nodes.push(walker.currentNode);
        nodes.forEach(translateTextNode);

        document.querySelectorAll('[alt], [placeholder], [aria-label]').forEach(function(el) {
            if (!el.closest('[data-lang-switch]')) translateAttributes(el);
        });

        // Language button shows the OTHER language
        document.querySelectorAll('[data-lang-switch]').forEach(function(btn) {
            btn.textContent = lang === 'fr' ? 'EN' : 'FR';
            btn.setAttribute('aria-label', lang === 'fr' ? 'Switch to English' : 'Passer en français');
            btn.setAttribute('lang', lang === 'fr' ? 'en' : 'fr');
        });

        try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
        document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: lang } }));
    }

    function savedLanguage() {
        try { return localStorage.getItem(STORAGE_KEY) || 'en'; } catch (e) { return 'en'; }
    }

    // Public helpers used by js/script.js
    window.BuildzegI18n = {
        t: translate,
        getLanguage: function() { return lang; },
        setLanguage: applyLanguage
    };

    document.querySelectorAll('[data-lang-switch]').forEach(function(btn) {
        btn.addEventListener('click', function() {
            applyLanguage(lang === 'fr' ? 'en' : 'fr');
        });
    });

    // This script is loaded at the end of <body>, so the page is already parsed
    applyLanguage(savedLanguage());
})();
